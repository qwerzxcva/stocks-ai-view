# engine 9: 日历效应 (全史 362 万日度样本验证, 2026-10-21)
# 周二 +0.110%/日, 周五 -0.015%, 周一 +0.071% → 周二/周一 加权, 周五减权
# 2月 +0.203% 最强 (春节效应), 1月 -0.079% 最弱, 9-11月强
DOW_W = {0: 1.05, 1: 1.15, 2: 0.85, 3: 0.95, 4: 0.70}   # Mon..Fri 乘数 (基于均值/总均值)
MON_W = {1: 0.7, 2: 1.4, 3: 1.0, 4: 1.05, 5: 0.95, 6: 0.75,
         7: 1.05, 8: 1.1, 9: 1.2, 10: 1.15, 11: 1.12, 12: 0.95}

def calendar_weight(d):
    """d: date. 返回该日荐股权乘数 (0.7-1.4)"""
    w = DOW_W.get(d.weekday(), 1.0) * MON_W.get(d.month, 1.0)
    return round(w, 3)
